// Downloads the GeoNames postal-code dataset for Slovakia and writes server/postal-data.mjs,
// so every PSČ resolves to exact coordinates. Data: GeoNames, CC BY 4.0 (https://www.geonames.org).
import { writeFileSync } from "node:fs";
import { inflateRawSync } from "node:zlib";

function unzipEntry(buffer, wanted) {
  let eocd = buffer.length - 22;
  while (eocd >= 0 && buffer.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  if (eocd < 0) throw Error("Neplatný ZIP súbor.");
  let p = buffer.readUInt32LE(eocd + 16);
  for (let i = buffer.readUInt16LE(eocd + 10); i > 0; i--) {
    const method = buffer.readUInt16LE(p + 10),
      size = buffer.readUInt32LE(p + 20),
      nameLength = buffer.readUInt16LE(p + 28),
      next = p + 46 + nameLength + buffer.readUInt16LE(p + 30) + buffer.readUInt16LE(p + 32),
      local = buffer.readUInt32LE(p + 42),
      name = buffer.toString("utf8", p + 46, p + 46 + nameLength);
    if (name === wanted) {
      const start = local + 30 + buffer.readUInt16LE(local + 26) + buffer.readUInt16LE(local + 28),
        data = buffer.subarray(start, start + size);
      return method === 8 ? inflateRawSync(data) : data;
    }
    p = next;
  }
  throw Error(wanted + " sa v archíve nenašiel.");
}
export function parseGeonames(text) {
  const out = {};
  for (const line of text.split("\n")) {
    const f = line.split("\t");
    if (f.length < 11 || f[0] !== "SK") continue;
    const zip = f[1].replace(/\s/g, ""),
      lat = Number(f[9]),
      lon = Number(f[10]);
    if (/^\d{5}$/.test(zip) && Number.isFinite(lat) && Number.isFinite(lon) && !out[zip])
      out[zip] = [Math.round(lat * 1e4) / 1e4, Math.round(lon * 1e4) / 1e4, f[2]];
  }
  return out;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const response = await fetch("https://download.geonames.org/export/zip/SK.zip");
  if (!response.ok) throw Error("Stiahnutie zlyhalo: HTTP " + response.status);
  const data = parseGeonames(unzipEntry(Buffer.from(await response.arrayBuffer()), "SK.txt").toString("utf8"));
  const count = Object.keys(data).length;
  if (count < 1000) throw Error("Dataset vyzerá neúplne (" + count + " PSČ).");
  writeFileSync(
    "server/postal-data.mjs",
    "// Generated by `npm run postal` from GeoNames (CC BY 4.0, https://www.geonames.org). Do not edit.\nexport const POSTAL = " +
      JSON.stringify(data) +
      ";\n",
  );
  console.log(`Uložených ${count} PSČ do server/postal-data.mjs.`);
}
